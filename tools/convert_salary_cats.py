"""Convert the five reference GIFs to RGB332 RLE frames (requires Pillow)."""
import argparse
from pathlib import Path
import shutil
from collections import deque
from PIL import Image


def cutout(image):
    """Remove edge-connected paper; keep the cat's enclosed white belly."""
    image = image.convert('RGBA')
    width, height = image.size
    pixels = list(image.getdata())
    outside = bytearray(width * height)
    queue = deque()
    def background(index):
        r, g, b, a = pixels[index]
        return a < 128 or min(r, g, b) >= 230
    def visit(index):
        if not outside[index] and background(index):
            outside[index] = 1
            queue.append(index)
    for x in range(width):
        visit(x); visit((height - 1) * width + x)
    for y in range(height):
        visit(y * width); visit(y * width + width - 1)
    def neighbors(index):
        x, y = index % width, index // width
        if x: yield index - 1
        if x + 1 < width: yield index + 1
        if y: yield index - width
        if y + 1 < height: yield index + width
    while queue:
        for index in neighbors(queue.popleft()): visit(index)
    # The supplied corner watermark is a separate pale neutral component.
    seen = bytearray(outside)
    keep = bytearray(width * height)
    for start in range(len(pixels)):
        if seen[start]: continue
        seen[start] = 1
        queue.append(start)
        component, ink = [], False
        while queue:
            index = queue.popleft()
            component.append(index)
            r, g, b, _ = pixels[index]
            ink |= min(r, g, b) < 140 or max(r, g, b) - min(r, g, b) > 35
            for other in neighbors(index):
                if not seen[other]:
                    seen[other] = 1
                    queue.append(other)
        if ink and len(component) >= 24:
            for index in component: keep[index] = 1
    result = Image.new('RGBA', image.size)
    result.putdata([pixel if keep[i] else (0, 0, 0, 0) for i, pixel in enumerate(pixels)])
    return result


def encode(pixels):
    result = bytearray()
    previous, count = None, 0
    for pixel in pixels:
        value = (pixel[0] & 0xe0) | ((pixel[1] >> 3) & 0x1c) | (pixel[2] >> 6)
        # Index zero is transparent; map opaque near-black to its nearest blue.
        value = 0 if pixel[3] < 128 else value or 1
        if value != previous or count == 255:
            if count:
                result.extend((count, previous))
            previous, count = value, 0
        count += 1
    if count:
        result.extend((count, previous))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    assets = root / 'assets/salary_cat'
    assets.mkdir(parents=True, exist_ok=True)
    data, frames, ranges = bytearray(), [], []
    for day in '一二三四五':
        source = args.source / f'周{day}.gif'
        if source.resolve() != (assets / source.name).resolve():
            shutil.copyfile(source, assets / source.name)
        start, elapsed = len(frames), 0
        with Image.open(source) as image:
            for index in range(image.n_frames):
                image.seek(index)
                # Keep original durations while limiting display updates to ~10 Hz.
                if elapsed and elapsed < 100 and index < image.n_frames - 1:
                    elapsed += image.info.get('duration', 70)
                    continue
                if len(frames) > start:
                    frames[-1][2] = max(70, elapsed)
                rgba = cutout(image).resize((112, 112), Image.Resampling.LANCZOS)
                packed = encode(rgba.getdata())
                frames.append([len(data), len(packed), 100])
                data.extend(packed)
                elapsed = image.info.get('duration', 70)
        frames[-1][2] = max(70, elapsed)
        ranges.append((start, len(frames) - start))
    (root / 'main/salary_cat.rle').write_bytes(data)
    header = ['// Generated by tools/convert_salary_cats.py; RGB332 RLE, 112x112.',
              '#pragma once', '#include <stdint.h>',
              'typedef struct { uint32_t offset; uint16_t length, duration; } salary_cat_frame_t;',
              'static const salary_cat_frame_t salary_cat_frames[] = {']
    header += [f'    {{{offset}, {length}, {duration}}},' for offset, length, duration in frames]
    header += ['};', 'static const uint16_t salary_cat_ranges[5][2] = {']
    header += [f'    {{{start}, {count}}},' for start, count in ranges]
    header += ['};', '']
    (root / 'main/salary_cat_frames.h').write_text('\n'.join(header), encoding='utf-8')
    print(f'{len(frames)} frames, {len(data):,} bytes in flash; 13,568-byte playback buffer.')


if __name__ == '__main__':
    main()
